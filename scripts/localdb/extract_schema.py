"""Pull the production schema dumps out of a Claude session log into schema.sql.

Usage: python3 -I extract_schema.py <session.jsonl> <out.sql>
The dumps are the catalog queries run against production (structure only).
"""
import json, re, sys

src, out = sys.argv[1], sys.argv[2]
found = {}

def walk(o):
    if isinstance(o, dict):
        for v in o.values():
            yield from walk(v)
    elif isinstance(o, list):
        for v in o:
            yield from walk(v)
    elif isinstance(o, str):
        yield o

for line in open(src):
    try:
        rec = json.loads(line)
    except Exception:
        continue
    for s in walk(rec):
        if "untrusted-data" not in s:
            continue
        # The tool result is itself JSON: {"result": "...<untrusted-data>[...]..."}
        if s.lstrip().startswith("{"):
            try:
                s = json.loads(s).get("result", s)
            except Exception:
                pass
        m = re.search(r"<untrusted-data-[0-9a-f-]+>\s*(\[.*\])\s*</untrusted-data", s, re.S)
        if not m:
            continue
        try:
            rows = json.loads(m.group(1))
        except Exception:
            continue
        if not rows or not isinstance(rows[0], dict):
            continue
        r = rows[0]
        if "tables" in r and "constraints" in r:
            found["tables"] = r
        elif "views" in r and "funcs" in r:
            found["views"] = r
        elif r.get("marker") == "FIELD_DOORS_DEF":
            found["field_doors"] = r["def"]

missing = [k for k in ("tables", "views", "field_doors") if k not in found]
if missing:
    sys.exit(f"missing dumps: {missing}")

t, v = found["tables"], found["views"]
seqs = sorted(set(re.findall(r"nextval\('([a-z_]+)'::regclass\)", t["tables"])))
parts = [
    "-- PowerEdge local schema: a copy of production's structure (no data).",
    "-- Generated by scripts/localdb/extract_schema.py from catalog queries.",
    "create extension if not exists pgcrypto;",
    "create extension if not exists \"uuid-ossp\";",
    "\n".join(f"create sequence if not exists public.{s};" for s in seqs),
    t["tables"],
    t["constraints"],
    t["fks"],
    t["indexes"],
    # Functions the views need first (cell_r/cell_c/norm_street), then views,
    # then doors_near (needs target_last_knock), then field_doors.
]
funcs = v["funcs"]
fn_blocks = [b.strip() for b in re.split(r"\n\n(?=CREATE OR REPLACE FUNCTION)", funcs) if b.strip()]
early = [b for b in fn_blocks if "doors_near" not in b.split("(")[0]]
late = [b for b in fn_blocks if "doors_near" in b.split("(")[0]]
parts += early
views = v["views"]
view_blocks = [b.strip() for b in re.split(r"\n\n(?=create (?:view|materialized view))", views) if b.strip()]
for b in view_blocks:
    b = b.rstrip(";") + ";"
    name = re.match(r"create (?:view|materialized view) (public\.\w+)", b).group(1)
    parts.append(b)
    parts.append(f"alter view {name} set (security_invoker = true);")
parts += late
parts.append(found["field_doors"].rstrip() + ";")
open(out, "w").write("\n\n".join(parts) + "\n")
print("wrote", out, "sequences:", seqs, "functions:", len(fn_blocks), "views:", len(view_blocks))
